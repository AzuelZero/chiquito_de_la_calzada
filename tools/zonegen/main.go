// Comando zonegen genera datecore/zones_data.go a partir del fichero
// zone1970.tab de la base de datos IANA.
//
// Uso:
//
//	go run ./tools/zonegen zone1970.tab > datecore/zones_data.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "uso: zonegen <zone1970.tab>")
		os.Exit(2)
	}
	f, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	var ids []string
	seen := map[string]bool{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 3 {
			continue
		}
		id := fields[2]
		if !seen[id] {
			seen[id] = true
			ids = append(ids, id)
		}
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	sort.Strings(ids)

	fmt.Println("// Code generated by tools/zonegen from zone1970.tab; DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package datecore")
	fmt.Println()
	fmt.Println("// canonicalZoneIDs son las zonas canónicas de la base IANA (zone1970.tab).")
	fmt.Println("var canonicalZoneIDs = []string{")
	for _, id := range ids {
		fmt.Printf("\t%q,\n", id)
	}
	fmt.Println("}")
}
